// HEADLESS: yes
// Measures std::vector vs std::list vs std::deque (the default container of
// std::queue) on REAL datapack data, read with the production loader: the
// files a server serves (base datapack + its biggest maincode), the maps of
// that maincode, the items, the monsters, plus the small FIFO the server
// Client keeps per player (DB callbacks, pending teleports).
// Containers: vector (push_back growth), vector_reserved (reserve(n) first, as a
// deserialiser does), list, deque. Metrics, per <dataset>.<container>:
//   build_ns_per_elem  ns      lower   construct by push_back, fixed time
//   scan_elems_per_s   1/s     higher  read-only full traversal, fixed time
//   heap_bytes         B       lower   heap really held by one built container
//   heap_blocks        blocks  lower   heap blocks of one built container
//   cpu_percent        %       lower   CPU over the cell (single thread: 100 = one core)
// FIFO, per fifo<depth>.<container>: ops_per_s (higher), allocs_per_op (lower),
// empty_heap_bytes (lower, what an EMPTY container already holds).
// Deterministic data; the timings are sampled (fixed-time window per cell).
//
// usage: benchmark_containers --datapack <dir> [--ms <window>] [--emit-esp32 <file.cpp> <max files>]
// --emit-esp32 writes the files + items datasets as C++ arrays for the ESP32
// firmware (benchmarkcontainers/esp32, no filesystem there) and exits.

